CREATE FUNCTION dbo.SomaValores (@tabela AS table (valor INT))
RETURNS FLOAT
AS
BEGIN
    DECLARE @soma FLOAT
    SET @soma = 0
    SELECT @soma = SUM(valor)
    FROM @tabela
    RETURN @soma
END


